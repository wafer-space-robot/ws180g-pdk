"""The design-rule manual: Markdown generated from the rule table alone.

`write_manual(table, out_path)` writes one section per rule group (the part of the rule id
before its first dot: a layer such as `nw`, an alias such as `df`, a group such as `sel`; in
the table's order, rules with no layer last, under "Whole layout") and one row per rule: id,
kind, layer expressions (aliases expanded, with the `edges` qualifier when the rule has
one), value, note (the derivation), evidence ids, margin applied (with its reason when one
is recorded), margin achieved (the author's figure, which the evidence report has verified
before the build writes the manual), composed-of, engines, condition and implied-by. Spec 3.6 point 2: no generator reads the evidence set, so the public rules
no field cites appear only on the evidence-report page. The output carries no date: the same
table gives the same bytes.
"""

import argparse
from decimal import Decimal
from pathlib import Path

from ws180g_rules.table import DEFAULT_VARIANT, RuleRow, RuleTable

GENERATOR = "ws180g_rules.manual"
NO_LAYER = "Whole layout"
HEADER = ("| id | kind | layers | value | note | evidence | margin applied | margin achieved "
          "| composed of | engines | condition | implied by |\n"
          "|---|---|---|---|---|---|---|---|---|---|---|---|")


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _dec(value: Decimal | None) -> str:
    return "" if value is None else format(value, "f")


def _codes(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items)


def _section(row: RuleRow) -> str | None:
    """The rule's group: the id up to its first dot (`df.w` -> `df`, an alias the layer
    expressions no longer show); None for a rule with no layer."""
    return row.id.split(".")[0] if row.layers else None


def _layers(row: RuleRow) -> str:
    text = ", ".join(str(e) for e in row.layers)
    if row.edges:
        text = "; ".join(filter(None, [text, f"edges {row.edges} {row.edge_layer or ''}".strip()]))
    return _cell(text)


def _line(row: RuleRow) -> str:
    value = f"{_dec(row.value)} {row.unit or ''}".strip() if row.value is not None else ""
    applied = _dec(row.margin)
    if row.margin_reason:
        applied = f"{applied} ({_cell(row.margin_reason)})"
    condition = row.condition or ""
    if row.module:
        condition = "; ".join(filter(None, [condition, f"module `{row.module}`"]))
    implied = f"`{row.implied_by}`" if row.implied_by else ""
    return (f"| `{row.id}` | {row.kind} | {_layers(row)} | {value} | {_cell(row.text)} "
            f"| {_codes(row.evidence)} "
            f"| {applied} | {_dec(row.margin_achieved)} | {_codes(row.composed_of)} "
            f"| {', '.join(row.engines)} | {_cell(condition)} | {implied} |")


def manual_text(table: RuleTable) -> str:
    """The manual of `table` as Markdown."""
    lines = [(f"<!-- Generated by {GENERATOR} from the {table.variant} rule table; "
              "do not edit. -->"), "",
             f"# {table.variant} design rules", "",
             (f"{len(table)} rules of variant `{table.variant}`, by the layer, alias or group "
              "each rule id starts with. A row gives what the rule measures (its kind and "
              "layer expressions, aliases expanded: `df` is `nd|pd`), its value and the note "
              "that derives it. Lengths in um, areas in um2. The margin applied is the ratio the value "
              "keeps over the largest public minimum (or under the smallest public "
              "maximum); the margin achieved is the ratio it reaches, checked by the "
              "evidence report. A rule with no engine is a generation parameter; "
              "\"implied by\" names the rule whose check covers it.")]
    sections: dict[str | None, list[RuleRow]] = {}
    for row in table.rows:
        sections.setdefault(_section(row), []).append(row)
    order = [s for s in sections if s is not None]
    if None in sections:
        order.append(None)
    for name in order:
        title = NO_LAYER if name is None else f"`{name}`"
        lines += ["", f"## {title}", "", HEADER]
        lines += [_line(row) for row in sections[name]]
    return "\n".join(lines) + "\n"


def write_manual(table: RuleTable, out_path: Path) -> Path:
    """Write the manual of `table` to `out_path` and return the path."""
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(manual_text(table), encoding="utf-8")
    return out_path


def main(argv: list[str] | None = None) -> int:
    """`ws180g-manual [--variant V] --out PATH`: write the design-rule manual of variant V."""
    from ws180g_process.load import load_process

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--variant", default=DEFAULT_VARIANT,
                        help=f"process variant (default: {DEFAULT_VARIANT})")
    parser.add_argument("--out", type=Path, required=True, help="output Markdown file")
    args = parser.parse_args(argv)
    print(write_manual(RuleTable.from_process(load_process(), args.variant), args.out))
    return 0
