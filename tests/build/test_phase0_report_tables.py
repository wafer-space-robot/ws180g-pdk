"""The exception tables of the Phase 0 gate report (`docs/phase-0-report.md`) equal the
current output of `tools/phase0_report_tables.py`, so the report cannot go stale when a code
constant (`EXPECTED_MARKERS`, `MAGIC_EXCEPTIONS`, the KLayout-only rules, `EXCLUDED`, the
regressions, the excluded GF deck files) changes. After such a change, rerun the script and
paste its output between the report's markers."""

import importlib.util
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "tools" / "phase0_report_tables.py"
REPORT = REPO / "docs" / "phase-0-report.md"
BEGIN = "<!-- BEGIN generated by `uv run tools/phase0_report_tables.py`; do not edit -->"
END = "<!-- END generated -->"


def _module():
    spec = importlib.util.spec_from_file_location("phase0_report_tables", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _report_block() -> str:
    text = REPORT.read_text(encoding="utf-8")
    assert text.count(BEGIN) == 1 and text.count(END) == 1, "the report needs one marker pair"
    return text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n") + "\n"


def test_report_tables_match_the_code():
    assert _report_block() == _module().tables()


def test_script_prints_the_tables():
    result = subprocess.run([sys.executable, str(SCRIPT)], cwd=REPO, capture_output=True,
                            text=True, check=True)
    assert result.stdout == _module().tables()


def test_tables_list_every_constant():
    from ws180g_precheck.gate import EXCLUDED
    from ws180g_rules.fixtures import EXPECTED_MARKERS
    from ws180g_tech.magic import MAGIC_EXCEPTIONS

    tables = _module().tables()
    for rid, name in [*EXPECTED_MARKERS, *MAGIC_EXCEPTIONS, *EXCLUDED]:
        assert f"`{rid}/{name}`" in tables
